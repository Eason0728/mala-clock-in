/* 薪酬挑錯第 5 項補洞：「滿六個月」那個月（第一個特休年度的起點，之前沒有舊年度）的手動列特休。
 *
 * 洞：第 5 項的規則「沒有逐日紀錄 → 週年日 16 號以後整筆算舊年度」，在第一個特休年度的起點沒有舊年度可收，
 *     那筆特休兩個年度都沒算到（已用 0），等於白休。
 * 規則（2026-11-11 補洞）：
 *   ① 沒有舊年度可收（這一期的起算日＝到職滿六個月那天）→ 那個月手動列的特休一律算進新年度（唯一存在的那一期），
 *      不看起算日幾號。
 *   ② 那個月有逐日紀錄時同理：起算日之前的日子不可以掉到不存在的年度，手動總時數整筆算進新年度。
 *   第二個年度以後（有舊年度可收）照第 5 項原規則，不變。
 *
 * 期望值全部照規則手算寫死（滿 6 個月 3 天＝24H、滿 1 年 7 天＝56H）。同仁全部虛構、只用代號。 */
const V = require('./helpers/payroll-vm.js');
const ST = 'SSLGF';
const NAME = '代號甲';
const fresh = (hire, input) => ({
  master: [V.ftEmp({ emp_id: 'E01', name: NAME, hire_date: hire })],
  input: input || [], run: [], item: [], config: [], holiday: [], bonus: [], audit: [], leave_type: [],
  store: [{ code: ST, name: '測試店', clock_ss_id: '', emp_prefix: '', active: 'true' }],
});
const manual = (ym, h) => ({ ym: ym, emp_id: 'E01', store: ST, hours: 176, annual_h: h, support: '[]', hours_manual: '' });
const lv = (d, h, kind, name) => ({ '日期': d, '姓名': name || NAME, '假別': kind || '特休假', '時數': h });
function info(hire, ym, input, leave) {
  const S = V.load({ data: fresh(hire, input), clock: { [ST]: { roster: [], approved: [], events: [], leave: leave || [], requests: [] } }, today: '2026-11-11' });
  return JSON.parse(JSON.stringify(S.call('payAnnualInfo', ym, ST).E01));
}
const S0 = V.load({ data: fresh('2026-04-20') });
const share = (...a) => S0.call('payAnnualManualShare_', ...a);

let p = 0, f = 0;
const chk = (n, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); ok ? p++ : f++;
  console.log((ok ? '✓ ' : '✗ ') + n + ': ' + JSON.stringify(got) + (ok ? '' : ' ← 應為 ' + JSON.stringify(want))); };
const pick = a => [a.ps, a.pe, a.quota_h, a.used_h, a.left_h, a.payout_h === undefined];

console.log('══ A　第一個特休年度的起點、沒有逐日紀錄：一律算進新年度 ══');
// 到職 2026-04-20 → 滿六個月 2026-10-20，第一期 2026-10-20～2027-04-19（3 天＝24H），之前沒有任何年度。
let a = info('2026-04-20', '2026-10', [manual('2026-10', 8)]);
chk('A1 到職 2026-04-20、2026-10 手動特休 8H：已用 8（不是 0）、剩 16、沒有舊年度結算', pick(a), ['2026-10-20', '2027-04-20', 24, 8, 16, true]);
a = info('2026-04-20', '2026-11', [manual('2026-10', 8)]);
chk('A1 隔月（2026-11）再看：已用 8、剩 16', [a.used_h, a.left_h], [8, 16]);
// 起算日 16 號（分界那一天）
a = info('2026-04-16', '2026-10', [manual('2026-10', 4)]);
chk('A2 到職 2026-04-16（起算日 16 號）、手動 4H：已用 4、剩 20', [a.used_h, a.left_h], [4, 20]);
// 月底到職：2025-08-31 → 滿六個月 2026-02-28（該月最後一天）
a = info('2025-08-31', '2026-02', [manual('2026-02', 8)]);
chk('A3 到職 2025-08-31（起算日 2026-02-28）、2026-02 手動 8H：已用 8、剩 16', [a.ps, a.used_h, a.left_h], ['2026-02-28', 8, 16]);
// 起算日 15 號以前：原本就算新年度（對照組）
a = info('2026-04-10', '2026-10', [manual('2026-10', 8)]);
chk('A4 到職 2026-04-10（起算日 10 號）：已用 8、剩 16（原本就對）', [a.used_h, a.left_h], [8, 16]);

console.log('\n══ B　第一個特休年度的起點、有逐日紀錄：起算日之前的日子也算進新年度 ══');
// 手動 8H；逐日 10/10 4H（起算日之前）＋10/25 4H → 沒有舊年度可收，8H 整筆算新年度。
a = info('2026-04-20', '2026-10', [manual('2026-10', 8)], [lv('2026-10-10', 4), lv('2026-10-25', 4)]);
chk('B1 逐日 10/10 4H＋10/25 4H：已用 8（不是 4）、剩 16', [a.used_h, a.left_h], [8, 16]);
a = info('2026-04-20', '2026-10', [manual('2026-10', 8)], [lv('2026-10-10', 8)]);
chk('B2 逐日只有 10/10 8H（全在起算日之前）：已用 8（不是 0）、剩 16', [a.used_h, a.left_h], [8, 16]);
a = info('2026-04-20', '2026-10', [manual('2026-10', 12)], [lv('2026-10-10', 2), lv('2026-10-25', 6)]);
chk('B3 手動 12H、逐日 2H＋6H：12H 整筆算新年度、剩 12', [a.used_h, a.left_h], [12, 12]);

console.log('\n══ C　純函式 payAnnualManualShare_ 的第 5 個參數（沒有舊年度）══');
const Q1 = { ps: '2026-10-20', pe: '2027-04-20' };
chk('C1 沒有舊年度、起算日 20 號、沒有逐日：8', share('2026-10', 8, Q1, [], true), 8);
chk('C2 沒有舊年度、逐日全在起算日之前：8', share('2026-10', 8, Q1, [{ d: '2026-10-10', h: 8 }], true), 8);
chk('C3 有舊年度（不帶第 5 個參數）、起算日 20 號、沒有逐日：0（歸舊年度，原規則）', share('2026-10', 8, Q1, []), 0);
chk('C4 有舊年度、逐日 10/10 4H＋10/25 4H：4（原規則）', share('2026-10', 8, Q1, [{ d: '2026-10-10', h: 4 }, { d: '2026-10-25', h: 4 }], false), 4);
chk('C5 沒有舊年度也不會多算：整個月在這一期之外＝0', share('2026-09', 8, Q1, [], true), 0);
chk('C6 沒有舊年度、這一期在這個月的月中結束（2027-04）：照原規則，20 號 ≥16 → 8', share('2027-04', 8, Q1, [], true), 8);

console.log('\n══ D　第二個年度以後不受影響（有舊年度可收）══');
// 到職 2025-10-20：2026-10 是第二個年度的起點，舊年度 2026-04-20～10-19（24H）存在 → 20 號整筆算舊年度。
a = info('2025-10-20', '2026-10', [manual('2026-10', 8)]);
chk('D1 到職 2025-10-20、2026-10 手動 8H：舊年度結算 16、新年度已用 0、剩 56', [a.payout_h, a.used_h, a.left_h], [16, 0, 56]);
a = info('2025-10-20', '2026-10', [manual('2026-10', 8)], [lv('2026-10-10', 4), lv('2026-10-25', 4)]);
chk('D2 同上、逐日 10/10 4H＋10/25 4H：結算 20、已用 4、剩 52', [a.payout_h, a.used_h, a.left_h], [20, 4, 52]);
// 第一期的尾端（2027-04，舊年度＝第一期）：到職 2026-04-20、2027-04 手動 8H，20 號 → 整筆算舊年度（第一期），結算 24−8＝16。
a = info('2026-04-20', '2027-04', [manual('2027-04', 8)]);
chk('D3 到職 2026-04-20、2027-04 手動 8H：算第一期（舊年度），結算 16、新年度已用 0、剩 56', [a.payout_h, a.used_h, a.left_h], [16, 0, 56]);

console.log(f ? `\n❌ ${f} 項失敗（通過 ${p}）` : `\n✅ 第一個特休年度起點的手動列特休歸屬全部正確 (${p}/${p})`);
process.exit(f ? 1 : 0);
