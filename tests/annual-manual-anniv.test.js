/* 薪酬挑錯第 5 項：手動工時的月份＋週年日在月中，那個月的特休只能算進一個年度（Eason 2026-11-11 確認）。
 *
 * 規則：
 *   ① 那個月的請假分頁（leave）有這個人的特休逐日紀錄 → 依日期切；手動總時數與逐日合計不同時，
 *      按逐日的比例分配手動總時數。
 *   ② 沒有逐日紀錄 → 週年日（幾號）≤15 整筆算新年度、≥16 整筆算舊年度。
 *   週年日是 1 號、其他月份、有日期的請假紀錄（沒有手動列的月份）行為都不變。
 *
 * 期望值全部照規則手算寫死（額度：滿 6 個月 3 天＝24H、滿 1 年 7 天＝56H、滿 2 年 10 天＝80H、滿 3 年 14 天＝112H）。
 * 同仁全部虛構、只用代號。 */
const V = require('./helpers/payroll-vm.js');
const ST = 'SSLGF';
const NAME = '代號甲';
const fresh = (hire, input) => ({
  master: [V.ftEmp({ emp_id: 'E01', name: NAME, hire_date: hire })],
  input: input || [], run: [], item: [], config: [], holiday: [], bonus: [], audit: [], leave_type: [],
  store: [{ code: ST, name: '測試店', clock_ss_id: '', emp_prefix: '', active: 'true' }],
});
const manual = (ym, h) => ({ ym: ym, emp_id: 'E01', store: ST, hours: 176, annual_h: h, support: '[]', hours_manual: '' });
const lv = (d, h, kind, name) => ({ '日期': d, '姓名': name || NAME, '假別': kind || '特休假', '時數': h });
function info(hire, ym, input, leave) {
  const S = V.load({ data: fresh(hire, input), clock: { [ST]: { roster: [], approved: [], events: [], leave: leave || [], requests: [] } }, today: '2026-11-11' });
  return JSON.parse(JSON.stringify(S.call('payAnnualInfo', ym, ST).E01));
}

let p = 0, f = 0;
const chk = (n, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); ok ? p++ : f++;
  console.log((ok ? '✓ ' : '✗ ') + n + ': ' + JSON.stringify(got) + (ok ? '' : ' ← 應為 ' + JSON.stringify(want))); };
const pick = a => [a.payout_h, a.used_h, a.left_h];   // 〔舊年度結算時數, 新年度已用, 新年度剩餘〕

console.log('══ A　沒有逐日紀錄：看週年日幾號 ══');
// 到職 2025-10-15：舊年度 2026-04-15～10-14（24H）、新年度 2026-10-15 起（56H）。週年日 15 號 → 8H 整筆算新年度。
let a = info('2025-10-15', '2026-10', [manual('2026-10', 8)]);
chk('A1 到職 10/15、10 月手動特休 8H：舊年度結算 24、新年度已用 8、剩 48', pick(a), [24, 8, 48]);
chk('A1 兩個年度合計 72（8H 只扣一次）', a.payout_h + a.left_h, 72);
// 到職 2023-07-03：舊年度 2025-07-03～2026-07-02（80H）、新年度 2026-07-03 起（112H）。週年日 3 號 → 40H 整筆算新年度。
a = info('2023-07-03', '2026-07', [manual('2026-07', 40)]);
chk('A2 到職 2023-07-03、7 月手動特休 40H：舊年度不扣（結算 80）、新年度扣 40（剩 72）', pick(a), [80, 40, 72]);
a = info('2023-07-03', '2026-08', [manual('2026-07', 40)]);
chk('A2 隔月（2026-08）再看：新年度已用 40、剩 72', [a.used_h, a.left_h], [40, 72]);
// 到職 2025-10-16：週年日 16 號 → 整筆算舊年度。舊年度結算 24−8＝16、新年度剩 56。
a = info('2025-10-16', '2026-10', [manual('2026-10', 8)]);
chk('A3 到職 10/16（週年日 16 號）：整筆算舊年度，結算 16、新年度已用 0、剩 56', pick(a), [16, 0, 56]);
// 到職 2025-10-20：週年日 20 號 → 整筆算舊年度。
a = info('2025-10-20', '2026-10', [manual('2026-10', 8)]);
chk('A4 到職 10/20（週年日 20 號）：整筆算舊年度，結算 16、新年度已用 0、剩 56', pick(a), [16, 0, 56]);
// 到職 2025-10-02：週年日 2 號 → 整筆算新年度。
a = info('2025-10-02', '2026-10', [manual('2026-10', 16)]);
chk('A5 到職 10/02（週年日 2 號）、16H：整筆算新年度，結算 24、已用 16、剩 40', pick(a), [24, 16, 40]);

console.log('\n══ B　那個月請假分頁有特休逐日紀錄：依日期切 ══');
// 到職 2025-10-15、手動 8H；逐日 10/10 4H（舊）＋10/20 4H（新）→ 舊 4、新 4。
a = info('2025-10-15', '2026-10', [manual('2026-10', 8)], [lv('2026-10-10', 4), lv('2026-10-20', 4)]);
chk('B1 逐日 10/10 4H＋10/20 4H（合計＝手動 8H）：結算 20、新年度已用 4、剩 52', pick(a), [20, 4, 52]);
// 手動 12H、逐日 10/10 2H＋10/20 6H（合計 8H，跟手動不同）→ 按 2:6 分 12H → 舊 3、新 9。
a = info('2025-10-15', '2026-10', [manual('2026-10', 12)], [lv('2026-10-10', 2), lv('2026-10-20', 6)]);
chk('B2 手動 12H、逐日 2H＋6H：按比例分 → 結算 21、新年度已用 9、剩 47', pick(a), [21, 9, 47]);
// 週年日 20 號（沒有逐日就整筆算舊年度），但逐日紀錄在 10/25（新年度）→ 照日期算新年度。
a = info('2025-10-20', '2026-10', [manual('2026-10', 8)], [lv('2026-10-25', 8)]);
chk('B3 週年日 20 號、逐日在 10/25：照日期算新年度，結算 24、已用 8、剩 48', pick(a), [24, 8, 48]);
// 週年日 15 號（沒有逐日就整筆算新年度），但逐日紀錄在 10/05（舊年度）→ 照日期算舊年度。
a = info('2025-10-15', '2026-10', [manual('2026-10', 8)], [lv('2026-10-05', 8)]);
chk('B4 週年日 15 號、逐日在 10/05：照日期算舊年度，結算 16、已用 0、剩 56', pick(a), [16, 0, 56]);
// 週年日當天（10/15）屬於新年度。
a = info('2025-10-15', '2026-10', [manual('2026-10', 8)], [lv('2026-10-14', 4), lv('2026-10-15', 4)]);
chk('B5 逐日 10/14 4H（舊）＋10/15 4H（新，週年日當天）：結算 20、已用 4、剩 52', pick(a), [20, 4, 52]);
// 別人的特休、自己的事假不算逐日紀錄 → 走「沒有逐日」：週年日 20 號整筆算舊年度。
a = info('2025-10-20', '2026-10', [manual('2026-10', 8)], [lv('2026-10-25', 8, '特休假', '代號乙'), lv('2026-10-26', 8, '事假')]);
chk('B6 那個月只有別人的特休、自己的事假：不算逐日紀錄，照週年日 20 號算舊年度', pick(a), [16, 0, 56]);
// 逐日紀錄只是用來切，不另外加計（同月以手動為準）。
a = info('2025-10-15', '2026-10', [manual('2026-10', 8)], [lv('2026-10-20', 4)]);
chk('B7 手動 8H、逐日只有 10/20 4H：8H 全算新年度、不另加 4H', pick(a), [24, 8, 48]);

console.log('\n══ C　不受影響的情況 ══');
// 週年日 1 號：到職 2025-10-01 → 舊年度 2026-04-01～09-30（9 月薪資結算）、新年度 2026-10-01 起。
a = info('2025-10-01', '2026-10', [manual('2026-10', 8)]);
chk('C1 週年日 1 號、10 月手動 8H：新年度已用 8、剩 48，10 月沒有結算時數', [a.payout_h === undefined, a.used_h, a.left_h], [true, 8, 48]);
a = info('2025-10-01', '2026-09', [manual('2026-10', 8)]);
chk('C1 同一人看 9 月：舊年度結算 24（10 月的 8H 不算進舊年度）', [a.payout_h, a.used_h, a.left_h], [24, 0, 24]);
a = info('2025-10-01', '2026-10', [manual('2026-10', 8)], [lv('2026-10-10', 4)]);
chk('C2 週年日 1 號、有逐日紀錄：仍以手動 8H 為準', [a.used_h, a.left_h], [8, 48]);
// 手動月份整個月都在舊年度（8 月）：照舊扣舊年度。
a = info('2025-10-15', '2026-10', [manual('2026-08', 8)]);
chk('C3 手動月份 2026-08（整月在舊年度）：結算 16、新年度已用 0、剩 56', pick(a), [16, 0, 56]);
// 手動月份整個月都在新年度（11 月）。
a = info('2025-10-15', '2026-11', [manual('2026-11', 8)]);
chk('C4 手動月份 2026-11（整月在新年度）：已用 8、剩 48', [a.used_h, a.left_h], [8, 48]);
// 沒有手動列，請假分頁有日期：照日期（第一階段回報的對照組）。
a = info('2025-10-15', '2026-10', [], [lv('2026-10-20', 8)]);
chk('C5 沒有手動列、請假分頁 10/20 8H：結算 24、已用 8、剩 48', pick(a), [24, 8, 48]);
a = info('2025-10-15', '2026-10', [], [lv('2026-10-10', 8), lv('2026-10-20', 4)]);
chk('C6 沒有手動列、請假分頁 10/10 8H＋10/20 4H：結算 16、已用 4、剩 52', pick(a), [16, 4, 52]);
// 跨週年日那個月是手動列、別的月份是請假分頁：兩邊各算各的。
a = info('2025-10-15', '2026-10', [manual('2026-10', 8)], [lv('2026-09-10', 8)]);
chk('C7 9 月請假分頁 8H（舊）＋10 月手動 8H（週年日 15 號→新）：結算 16、已用 8、剩 48', pick(a), [16, 8, 48]);

console.log(f ? `\n❌ ${f} 項失敗（通過 ${p}）` : `\n✅ 手動月份跨週年日的特休歸屬全部正確 (${p}/${p})`);
process.exit(f ? 1 : 0);
